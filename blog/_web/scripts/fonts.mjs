// Runs before webpack. Cuts each web font in fonts/ down to the characters
// the site actually uses, writing the results to fonts/subset/ (which
// fonts.scss points at). Hinting and OpenType features are kept, so
// rendering is unchanged; only characters the site never uses are dropped.
//
// It also writes scss/includes/_font-range.scss, the matching unicode-range,
// so a character the scan misses is drawn in a fallback font rather than as
// a blank box.
//
// It reads the sources (posts, layouts, includes, pages, _config.yml)
// rather than the built HTML: webpack names the font files by content hash,
// so the subsets have to exist before webpack runs, which is before Jekyll.
// The sources are a superset of what is rendered, which is fine.

import subsetFont from "subset-font";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const blogRoot = path.resolve(webRoot, "..");
const fontDir = path.join(webRoot, "fonts");
const subsetDir = path.join(fontDir, "subset");
const rangeFile = path.join(webRoot, "scss", "includes", "_font-range.scss");

// Build output, tooling and dependencies: nothing here is rendered text.
const SKIP_DIRS = new Set([
  "_web",
  "_site",
  "assets",
  "vendor",
  "node_modules",
  "pagefind",
]);
const SOURCE = /\.(md|markdown|html|yml)$/;

// Always included: all of printable ASCII (cheap, and covers code, URLs and
// dates), a no-break space, and what kramdown's typographic conversion
// produces from plain quotes, dashes and dots, which isn't in the sources.
const ALWAYS =
  Array.from({ length: 0x7f - 0x20 }, (_, i) =>
    String.fromCharCode(0x20 + i),
  ).join("") + " ‘’“”–—…«»";

// Named entities used in the sources, or plausibly soon. An unknown one is
// reported rather than guessed at; unicode-range covers it meanwhile.
const ENTITIES = {
  amp: "&",
  lt: "<",
  gt: ">",
  quot: '"',
  apos: "'",
  nbsp: " ",
  ndash: "–",
  mdash: "—",
  hellip: "…",
  lsquo: "‘",
  rsquo: "’",
  ldquo: "“",
  rdquo: "”",
  laquo: "«",
  raquo: "»",
  pound: "£",
  euro: "€",
  copy: "©",
  reg: "®",
  trade: "™",
  deg: "°",
  times: "×",
  middot: "·",
  sect: "§",
};

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || SKIP_DIRS.has(entry.name)) {
      continue;
    }
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      yield* walk(full);
    } else if (SOURCE.test(entry.name)) {
      yield full;
    }
  }
}

function decodeEntities(text, file) {
  return text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (match, name) => {
    if (name.startsWith("#x") || name.startsWith("#X")) {
      return String.fromCodePoint(parseInt(name.slice(2), 16));
    }
    if (name.startsWith("#")) {
      return String.fromCodePoint(parseInt(name.slice(1), 10));
    }
    const decoded = ENTITIES[name.toLowerCase()];
    if (decoded == null) {
      console.warn(`fonts: unknown entity ${match} in ${file}`);
      return match;
    }
    return decoded;
  });
}

const chars = new Set(ALWAYS);
for await (const file of walk(blogRoot)) {
  const text = decodeEntities(await readFile(file, "utf8"), file);
  for (const ch of text) {
    if (ch.codePointAt(0) >= 0x20) {
      chars.add(ch);
    }
  }
}
const text = [...chars].join("");

/** U+20-7E, U+A0, U+A3, ... from the code points in use. */
function unicodeRange(codePoints) {
  const sorted = [...codePoints].sort((a, b) => a - b);
  const ranges = [];
  for (let i = 0; i < sorted.length; i++) {
    const start = sorted[i];
    while (sorted[i + 1] === sorted[i] + 1) {
      i++;
    }
    const hex = (n) => n.toString(16).toUpperCase();
    ranges.push(
      start === sorted[i]
        ? `U+${hex(start)}`
        : `U+${hex(start)}-${hex(sorted[i])}`,
    );
  }
  return ranges.join(", ");
}
const range = unicodeRange([...chars].map((c) => c.codePointAt(0)));

await mkdir(subsetDir, { recursive: true });
let before = 0;
let after = 0;
for (const name of await readdir(fontDir)) {
  if (!name.endsWith(".woff2")) {
    continue;
  }
  const original = await readFile(path.join(fontDir, name));
  const subset = await subsetFont(original, text, { targetFormat: "woff2" });
  await writeFile(path.join(subsetDir, name), subset);
  before += original.length;
  after += subset.length;
}

await writeFile(
  rangeFile,
  "// Generated by scripts/fonts.mjs; do not edit.\n" +
    `$font-unicode-range: unquote("${range}");\n`,
);

const nonAscii = [...chars].filter((c) => c.codePointAt(0) > 0x7e).join("");
console.log(
  `fonts: ${chars.size} characters (non-ASCII: ${nonAscii}); ` +
    `${(before / 1024).toFixed(1)} KB -> ${(after / 1024).toFixed(1)} KB`,
);
